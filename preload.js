'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lensa', {
  getState: () => ipcRenderer.invoke('get-state'),
  analyze: () => ipcRenderer.invoke('analyze'),
  analyzeRegion: () => ipcRenderer.invoke('analyze-region'),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  askText: (text) => ipcRenderer.invoke('ask-text', text),
  setShortAnswers: (on) => ipcRenderer.invoke('set-short-answers', on),
  setClipboardWatch: (on) => ipcRenderer.invoke('set-clipboard-watch', on),
  setVoiceCommand: (on) => ipcRenderer.invoke('set-voice-command', on),
  voiceSegment: (audio) => ipcRenderer.send('voice-segment', audio),
  onVoiceListen: (cb) => ipcRenderer.on('voice-listen', (_e, on) => cb(on)),
  setAlwaysOnTop: (on) => ipcRenderer.invoke('set-always-on-top', on),
  setHintMode: (on) => ipcRenderer.invoke('set-hint-mode', on),
  setModel: (model) => ipcRenderer.invoke('set-model', model),
  setSaveHistory: (on) => ipcRenderer.invoke('set-save-history', on),
  historyList: () => ipcRenderer.invoke('history-list'),
  historyDue: () => ipcRenderer.invoke('history-due'),
  historyReview: (id, rating) => ipcRenderer.invoke('history-review', id, rating),
  historyDelete: (id) => ipcRenderer.invoke('history-delete', id),
  historyClear: () => ipcRenderer.invoke('history-clear'),
  practiceGenerate: (kategori, focusTopics) => ipcRenderer.invoke('practice-generate', { kategori, focusTopics }),
  practiceRecord: (question, chosen) => ipcRenderer.invoke('practice-record', { question, chosen }),
  practiceClear: () => ipcRenderer.invoke('practice-clear'),
  statsGet: () => ipcRenderer.invoke('stats-get'),
  saveApiKey: (key) => ipcRenderer.invoke('save-api-key', key),
  clearApiKey: () => ipcRenderer.invoke('clear-api-key'),
  setConnection: (mode) => ipcRenderer.invoke('set-connection', mode),
  saveFreeKey: (provider, key) => ipcRenderer.invoke('save-free-key', provider, key),
  clearFreeKey: (provider) => ipcRenderer.invoke('clear-free-key', provider),
  serverAuth: (fields) => ipcRenderer.invoke('server-auth', fields),
  serverProfile: () => ipcRenderer.invoke('server-profile'),
  serverLogout: () => ipcRenderer.invoke('server-logout'),
  onStatus: (cb) => ipcRenderer.on('status', (_e, s) => cb(s)),
  onResult: (cb) => ipcRenderer.on('result', (_e, r) => cb(r)),
  onHistoryChanged: (cb) => ipcRenderer.on('history-changed', () => cb()),
});
